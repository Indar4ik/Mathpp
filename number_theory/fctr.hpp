// root = floor(sqrt(c)); возвращает true, если c — точный квадрат.
// Поправка на ошибку double идёт через умножение, а не деление: floor(sqrt c) заведомо
// не больше 2^32-1 (ведь (2^32)^2 = 2^64 > c), поэтому после зажима r в этот предел
// r*r уже не переполняется, а (r+1)*(r+1) прикрыто проверкой r < 2^32-1. Деления тут
// стоили дорого: в цикле Ферма is_square вызывается на 18% итераций и съедала почти
// половину ступени — замена дала x1.77 на ступени.
inline bool is_square(uint64_t c, uint64_t& root) noexcept {
    constexpr uint64_t RMAX = 0xFFFFFFFFull;               // floor(sqrt(2^64 - 1))
    uint64_t r = static_cast<uint64_t>(std::sqrt(static_cast<double>(c)));
    if (r > RMAX) r = RMAX;
    while (r * r > c) --r;                          // r*r > c
    while (r < RMAX && (r + 1) * (r + 1) <= c) ++r;  // (r+1)^2 <= c
    root = r;
    return r * r == c;
}

// Предрасчёт наибольшей степени q^e <= 2^B для каждого простого q <= 2^B. Кэш на B.
// Показатель считается циклом, а не через log2: floor(B / floor(log2 q)) ЗАВЫШАЕТ его,
// потому что floor(log2 q) занижает log2 q (для q = 3 это 1 вместо 1.585, и при B = 10
// выходит 3^10 = 59049 вместо 3^6 = 729 — уже за пределом 2^10, а при B >= 41 ещё и за
// пределом uint64). Делений тут бояться нечего: расчёт одноразовый и кэшируется.
inline const std::vector<uint64_t>& pm1_powers(uint32_t B) noexcept {
    [[assume(B >= 2 && B < 32)]];
    static uint32_t cached_B = 0;
    static std::vector<uint64_t> powers;
    if (B != cached_B) {
        const uint64_t limit = 1ull << B;
        powers.clear();
        powers.reserve(static_cast<size_t>(1.5 * static_cast<double>(limit) / B));
        for (const uint32_t &p : sieve(static_cast<uint32_t>(limit))) {
            uint64_t e = p;
            while (e <= limit / p) e *= p;      // наибольшая степень p, не превосходящая 2^B
            powers.push_back(e);
        }
        cached_B = B;
    }
    return powers;
}

// Pollard p-1: ищет нетривиальный делитель нечётного составного n.
// Идея (малая теорема Ферма): если (p-1) | M, то p | a^M - 1, значит p | gcd(a^M - 1, n).
// M строим неявно: возводим a в q^(макс степень <= B) по всем простым q <= B.
// gcd дорогой, поэтому берём его не на каждом простом, а раз в BATCH шагов: аккумулятор
// "залипает" (как только a ≡ 1 (mod p), таким и остаётся), поэтому gcd(a-1, n) на границе
// блока ловит p, созревшее в любом месте блока.
// При gcd == n (перелёт: >=2 делителя созрели в одном блоке) нужен ПЕРВЫЙ индекс, где
// gcd перестал быть единицей. Предикат монотонен по j - как только a == 1 (mod p), таким
// и остаётся, дальнейшие возведения единицу не меняют, - поэтому ищем бинпоиском по
// сохранённым состояниям аккумулятора, как в pollard_rho_batch. Пересчитывать блок
// пошагово здесь особенно дорого: каждый шаг это M.pow, а не одно умножение.
// BATCH оставлен 64: на 128 блок перелетает дальше и общий счёт хуже (x0.6-0.8).
// Возвращает делитель в (1, n) или 0, если p-1 не B-гладкое (тогда падаем в ferma).
inline uint64_t pollard_pm1(uint64_t n, uint32_t B) noexcept {
    [[assume((n & 1ull) == 1ull)]];
    constexpr int BATCH = 64;
    const std::vector<uint64_t>& powers = pm1_powers(B);

    mont M(n);
    std::array<uint64_t, BATCH> as;                          // состояния аккумулятора в блоке
    uint64_t a = M.add(M.one, M.one);                        // основание a = 2 в Montgomery-форме
    const size_t sz = powers.size();
    for (size_t i = 0; i < sz; i += BATCH) {
        const size_t block_end = std::min(i + BATCH, sz);
        for (size_t j = i; j < block_end; ++j) as[j - i] = a = M.pow(a, powers[j]);    // a = a^(q^k)

        uint64_t g = std::gcd(M.from(a) - 1, n);
        if (g == 1) continue;                       // в блоке делитель не созрел, дальше
        if (g != n) return g;                       // нашли нетривиальный делитель

        // Перелёт (g == n): бинпоиск первого j с gcd(a_j - 1, n) != 1.
        uint32_t lo = 0, hi = static_cast<uint32_t>(block_end - i) - 1;
        while (lo < hi) {
            uint32_t mid = (lo + hi) >> 1;
            if (std::gcd(M.from(as[mid]) - 1, n) != 1ull) hi = mid;
            else lo = mid + 1;
        }
        const uint64_t d = std::gcd(M.from(as[lo]) - 1, n);
        return d == n ? 0 : d;                      // одно простое созрело сразу на всё n -> пас
    }
    return 0;                                        // p-1 не B-гладкое
}

// Гарантированный fallback: перебор делителей с колесом mod 30030 (как sqrt_fctr).
// Дописывает простые множители n в factors БЕЗ очистки. Всегда даёт полное
// разложение за O(sqrt(n)). Используется, когда p-1 и Ферма не справились.
inline void trial_divide_all(uint64_t n, std::vector<uint64_t> &factors) noexcept {
    [[assume(n > 30030ull)]];
    [[assume((n & 1ull) == 1ull)]];

    uint64_t i = 30047;
    unsigned idx = 0;
    while (i * i <= n) {
        while(true){
            uint64_t m = n;
            uint64_t q = n / i;
            uint64_t r = n % i;
            n = r ? m : q;
            if (r != 0) break;
            factors.push_back(i);
        }
        i += WHEEL[idx];
        if (++idx == WHEEL_SIZE) idx = 0;
    }
    if (n > 1) factors.push_back(n);
}

// Порог ленивого шага: он держит x и p в [0, 2m), для чего нужно 4m <= R.
// Подробнее: приводить x и p к [0, n) незачем -
// gcd не различает представителей по модулю n (gcd(a, n) = gcd(a%n, n)),
// поэтому достаточно удержать величины в границах контракта redc_lazy.
// Добавка к квадрату берётся ЛИТЕРАЛЬНАЯ (c, а не to(c)). В Montgomery-форме хранимое
// x означает истинный вычет x*R^{-1}, так что это полином x^2 + c*R^{-1} - алгоритму
// всё равно, какая константа, лишь бы не 0 и не -2 по модулю n. Зато добавка вместо
// «почти m» становится единицей, и инвариант ужимается с x < 3m до x < 2m.
// В общем виде при инварианте x <= k*m контракт redc_lazy требует k^2*m < R, а
// устойчивость (k^2*m^2 + (R-1)m)/R + c <= k*m даёт m <= R(k-1)/k^2. С формой Монтгомери
// вместо c стояло бы m, и было бы R(k-2)/k^2 - тогда оба условия сходятся в k = 3 (R/9).
// С литеральной добавкой связывает контракт, минимальное допустимое k равно 2, отсюда R/4:
// ленивый путь покрывает 25% диапазона uint64 вместо 11%. Совпадает с общим LAZY_MAX.
inline constexpr uint64_t RHO_LAZY_MAX = LAZY_MAX;

// Один проход Pollard-ро (Брент) по полиному x^2 + c с батчингом gcd: произведение
// разностей копится по модулю n, gcd берётся раз в BATCH шагов, при перелёте
// (d == n) первый «плохой» индекс ищется бинпоиском по частичным произведениям.
// LAZY снимает с критического пути обе условные коррекции (годится при n <= RHO_LAZY_MAX).
// Контракт: n нечётное и СОСТАВНОЕ (на простом отказывает любое c, съев ~sqrt(n) шагов),
// 0 < c < n. Фактический полином - x^2 + c*R^{-1} (см. RHO_LAZY_MAX про литеральную
// добавку); один и тот же в обеих ветках, чтобы поведение не менялось на пороге.
// Возвращает делитель в (1, n) либо 0, если ро зациклилась.
template <bool LAZY>
inline uint64_t rho_batch_impl(uint64_t n, const uint64_t c) noexcept {
    [[assume((n & 1ull) == 1ull)]];

    constexpr uint32_t BATCH = 128;
    mont M(n);
    std::array<uint64_t, BATCH> ps;                 // частичные произведения блока
    uint32_t i = 0u;
    uint64_t x = M.add(M.one, M.one), anchor = x, p = M.one, d;

    while (true){
        for (uint32_t j = 0; j < BATCH; ++j) {
            if (!(i & (i - 1u))) anchor = x;
            if constexpr (LAZY) {
                x = M.mul_lazy(x, x) + c;
                p = M.mul_lazy(p, x > anchor ? x - anchor : anchor - x);
            } else {
                x = M.add(M.mul(x, x), c);
                p = M.mul(p, x > anchor ? x - anchor : anchor - x);
            }
            ps[j] = p;
            ++i;
        }

        d = std::gcd(p, n);
        if (d == 1ull) continue;                    // в блоке ничего не созрело
        if (d != n) return d;

        // Перелёт: первый j с gcd(ps[j], n) != 1.
        uint32_t lo = 0, hi = BATCH - 1;
        while (lo < hi) {
            uint32_t mid = (lo + hi) >> 1;
            if (std::gcd(ps[mid], n) != 1ull) hi = mid;
            else lo = mid + 1;
        }
        d = std::gcd(ps[lo], n);
        return d == n ? 0 : d;                      // одна разность делится на всё n -> пас
    }
}

// Перебор полиномов: c = 1 помогает в 99.84% случаев, c = 2 добивает до 99.996%,
// c = 3 - до 100% (проверено на 851k нечётных составных до 2e6, отдельно на p^2, p^3
// и на полупростых вплотную к порогу 2^62). Шагов впустую на неудачных c около 0.1%
// от полезных, так что ретрай бесплатен.
// Отсеивается только c, кратное n (тогда полином вырождается в x^2 с короткой орбитой).
// Второе вырождение, x^2 - 2, отвечает эффективному c*R^{-1} == -2, то есть n | 2^65 + c;
// такие n в диапазоне есть (2^65+1 = 11 * 3353953467947191203), но все составные и все
// снимаются следующим c, а стоит промах ~BATCH шагов - проверять дешевле не выйдет.
// Лимит - страховка от зависания: гарантии, что какой-то c сработает, нет, а на
// ПРОСТОМ n отказывают все, съедая ~sqrt(n) шагов каждый. После лимита отдаём 0,
// и вызывающий (ferma_fctr) падает в гарантированный trial_divide_all.
inline uint64_t pollard_rho(uint64_t n) noexcept {
    [[assume((n & 1ull) == 1ull)]];
    if (n <= 1) return 1ull;

    for (uint64_t c = 1; c <= 8; ++c) {
        const uint64_t cn = c % n;                  // контракт rho_batch_impl: 0 < c < n
        if (cn == 0) continue;
        const uint64_t d = n <= RHO_LAZY_MAX ? rho_batch_impl<true>(n, cn) : rho_batch_impl<false>(n, cn);
        if (d) [[likely]] return d;
    }
    return 0;
}

// Рекурсивный разбор составного n (мелочь уже снята колесом в balance_fctr).
// Лесенка «дёшево и точечно -> гарантированно и медленно», на каждом сплите
// рекурсия по обеим частям (делитель может быть составным):
//   1) Ферма        — близкие делители p ~ q (сбалансированное n);
//   2) Pollard-ро   — общий случай, ~n^(1/4);
//   3) перебор      — гарантированный финиш за O(sqrt n).
// pollard_pm1 в лесенке НЕ участвует: на 64 битах меньший множитель <= 2^32, то есть
// ро укладывается в ~2^16 шагов при любом входе (~0.23 мс в худшем случае), а стадия 1
// p-1 с B = 10^6 стоит ~5 мс ВСЕГДА, найдёт она что-нибудь или нет. Функция оставлена
// в файле: на модулях шире 64 бит, где sqrt(p) уже дорог, она снова осмысленна.
inline void ferma_fctr(uint64_t n, std::vector<uint64_t> &factors) noexcept {
    if (n <= 1ull) return;
    if (is_prime(n)) { factors.push_back(n); return; }

    // Ступень 1 — Ферма: n = a^2 - r^2 = (a-r)(a+r), перебираем a = ceil(sqrt n), +1, +2, ...
    // Ферма делает ~(p-q)^2/(8 sqrt n) шагов, то есть бьёт ро (~n^(1/4)) только при
    // |p - q| < ~n^(3/8). Дальше он всё равно проиграет, поэтому cap маленький:
    // на близких множителях 2^12 ловит всё то же, что и n^(1/3) (x16.6 против ро),
    // а на промахе стоит 8% вместо 12-кратного проигрыша.
    const uint64_t cap = std::min<uint64_t>(static_cast<uint64_t>(std::cbrt(static_cast<double>(n))) + 1, 4096);
    uint64_t a, r, c;
    if (is_square(n, a)) c = 0;            // n — точный квадрат: a = sqrt(n), сразу сплит a*a
    else { ++a; c = a * a - n; }          // a = ceil(sqrt n); при a == 2^32 mod-арифметика даёт верный c
    for (uint64_t step = 0; step < cap; ++step) {
        if (SQ_MASK >> (c & 63ull) & 1ull) [[unlikely]] {
            if (is_square(c, r)) {
                ferma_fctr(a - r, factors);
                ferma_fctr(a + r, factors);
                return;
            }
        }
        c += (a++ << 1) + 1;
    }

    // Ступень 2 — Pollard-ро: рабочая лошадь, ~n^(1/4) от МЕНЬШЕГО множителя.
    // На 64 битах меньший множитель <= 2^32, то есть ро укладывается в ~2^16 шагов
    // всегда — поэтому она стоит раньше p-1, чей проход по простым до 10^6
    // обходится дороже при любом раскладе.
    if (uint64_t g = pollard_rho(n)) {
        ferma_fctr(g, factors);
        ferma_fctr(n / g, factors);
        return;
    }

    // Ступень 3 — гарантированный финиш: перебор делителей колесом, O(sqrt n).
    trial_divide_all(n, factors);
}

inline void balance_fctr(uint64_t n, std::vector<uint64_t> &factors) noexcept {
    if (n <= 1) return;
    factors.clear();
    factors.reserve(64);

    if (is_prime(n)){
        factors.push_back(n);
        return;
    }

    int twos = std::countr_zero(n);
    n >>= twos;
    for (int i = 0; i < twos; ++i) factors.push_back(2);
    while (n % 3 == 0) { factors.push_back(3); n /= 3; }
    while (n % 5 == 0) { factors.push_back(5); n /= 5; }
    while (n % 7 == 0) { factors.push_back(7); n /= 7; }
    while (n % 11 == 0) { factors.push_back(11); n /= 11; }
    while (n % 13 == 0) { factors.push_back(13); n /= 13; }

    uint64_t i = 17;

    // Отсечка i*i > n обязательна: без неё колесо крутит все 5760 позиций до 30030
    // независимо от n, даже когда остаток давно простой. Это x53 на мелких n и x8.6
    // на n < 1e9; на 64-битных входах колесо и так проходится целиком (x1.01).
    // После выхода по отсечке n либо 1, либо простое — ferma_fctr разберёт оба случая.
    for (uint64_t idx = 0ull; idx < WHEEL_SIZE && i * i <= n; ++idx){
        while (true){
            uint64_t m = n;
            uint64_t q = n / i;
            uint64_t r = n % i;
            n = r ? m : q;
            if (r != 0) break;
            factors.push_back(i);
        }
        i += WHEEL[idx];
    }

    ferma_fctr(n, factors);
    return;
}

